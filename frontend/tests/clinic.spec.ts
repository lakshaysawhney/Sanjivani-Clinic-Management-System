import { test, expect, type Page } from '@playwright/test'
const password=process.env.E2E_PASSWORD!
async function login(page:Page,user='demo_reception'){
 await page.goto('/')
 await page.getByLabel('Username',{exact:true}).fill(user)
 await page.getByLabel('Password',{exact:true}).fill(password)
 await page.getByRole('button',{name:'Sign in',exact:true}).click()
 await expect(page.getByRole('heading',{name:/Daily schedule|My schedule/})).toBeVisible()
}
test('receptionist creates a patient, independent plan, booking, publication and payment',async({page})=>{
 await login(page)
 await page.getByRole('link',{name:'Patients',exact:true}).click()
 await page.getByRole('button',{name:'New patient'}).click()
 const name='Synthetic Browser '+Date.now()
 await page.getByLabel('Child’s full name').fill(name)
 await page.getByLabel('Expected sessions per week').fill('3')
 await page.getByLabel('Expected sessions per month').fill('14')
 await page.getByRole('button',{name:'Save patient',exact:true}).click()
 await page.getByLabel('Search patients').fill(name)
 await page.getByRole('link',{name,exact:true}).click()
 await expect(page.getByRole('heading',{name,exact:true})).toBeVisible()
 await page.getByRole('button',{name:'Record payment',exact:true}).click()
 await page.getByLabel('Amount in INR').fill('5000')
 await page.getByLabel('Method, reference and notes').fill('Synthetic browser payment')
 await page.getByRole('button',{name:'Record transaction',exact:true}).click()
 await expect(page.getByText('₹5,000.00').first()).toBeVisible()
 await page.getByRole('button',{name:/View Financial Details/}).click()
 await expect(page.getByText('Synthetic browser payment')).toBeVisible()
 await page.getByRole('link',{name:'Daily Schedule',exact:true}).click()
 await page.getByRole('button',{name:'Next day',exact:true}).click()
 const day=await page.getByLabel('Schedule date').inputValue()
 if(new Date(day+'T12:00:00').getDay()===0)await page.getByRole('button',{name:'Next day',exact:true}).click()
 const available=page.locator('.slot.free:not(:disabled)').first()
 await available.click()
 await page.getByLabel('Search for a patient').fill(name)
 await page.getByRole('button',{name:new RegExp(name)}).click()
 await page.getByRole('button',{name:'Save appointment',exact:true}).click()
 await expect(page.locator('.cell-name').filter({hasText:name})).toBeVisible()
 const publish=page.getByRole('button',{name:'Publish schedule',exact:true})
 if(await publish.isVisible())await publish.click()
 await expect(page.getByText('Published',{exact:true})).toBeVisible()
 await expect(page.getByRole('link',{name:'Staff',exact:true})).toHaveCount(0)
})
